    {
        Undefined = 0,
        UtmA = 1,
        UtmB = 2,
        UtmC = 3,
        UtmD = 4,
        UtmE = 5,
        UtmF = 6,
        UtmG = 7,
        UtmH = 8,
        UtmJ = 9,
        UtmK = 10,
        UtmL = 11,
        UtmM = 12,
        UtmN = 13,
        UtmP = 14,
        UtmQ = 15,
        UtmR = 16,
        UtmS = 17,
        UtmT = 18,
        UtmU = 19,
        UtmV = 20,
        UtmW = 21,
        UtmX = 22,
        UtmY = 23,
        UtmZ = 24
    }
}


